export function complaintCsvRows(dataset: AnalyticsDataset): CsvRow[] {
  const scope = makeScope(dataset);
  const rows = dataset.complaints
    .filter(
      (c) =>
        complaintInScope(c, scope) &&
        c.createdAt >= dataset.period.start &&
        c.createdAt < dataset.period.end
    )
    .map((c) => {
      const validResolution = c.resolvedAt && c.resolvedAt >= c.createdAt ? c.resolvedAt : null;
      const days = validResolution
        ? (validResolution.getTime() - c.createdAt.getTime()) / 86_400_000
        : null;
      return [
        c.id,
        c.createdAt.toISOString(),
        c.district ?? (c.business?.district ?? ""),
        c.business?.name ?? "",
        c.type ?? "unspecified",
        c.status,
        c.anonymous ? "yes" : "no",
        c.assignedOfficer?.name ?? "",
        c.assignedAt?.toISOString() ?? "",
        c.investigationStartedAt?.toISOString() ?? "",
        c.inspectionAt?.toISOString() ?? "",
        c.resolvedAt?.toISOString() ?? "",
        c.slaDays,
        days === null ? "" : Number(days.toFixed(2)),
        days === null ? "not resolvable" : days <= c.slaDays ? "within SLA" : "breached",
      ] as CsvRow;
    });
  return [
    [
      "Complaint ID",
      "Created at",
      "District",
      "Business",
      "Type",
      "Status",
      "Anonymous",
      "Assigned officer",
      "Assigned at",
      "Investigation started at",
      "Inspection at",
      "Resolved at",
      "SLA days",
      "Resolution days",
      "SLA outcome",
    ],
    ...rows,
  ];
}

export function inspectionCsvRows(dataset: AnalyticsDataset): CsvRow[] {
  const scope = makeScope(dataset);
  const start = dataset.period.start;
  const end = dataset.period.end;
  const rows = dataset.inspections
    .filter(
      (insp) =>
        inspectionInScope(insp, scope) &&
        ((insp.scheduledAt >= start && insp.scheduledAt < end) ||
          (insp.completedAt && insp.completedAt >= start && insp.completedAt < end))
    )
    .map((insp) => {
      const days =
        insp.completedAt && insp.completedAt >= insp.scheduledAt
          ? (insp.completedAt.getTime() - insp.scheduledAt.getTime()) / 86_400_000
          : null;
      const critical = insp.violations.filter((v) => v.severity === "critical").length;
      return [
        insp.id,
        insp.business.name,
        insp.business.district,
        insp.business.category,
        insp.officer?.name ?? "",
        insp.status,
        insp.scheduledAt.toISOString(),
        insp.completedAt?.toISOString() ?? "",
        days === null ? "" : Number(days.toFixed(2)),
        insp.violations.length,
        critical,
        insp.violations.map((v) => v.type).join(" | "),
      ] as CsvRow;
    });
  return [
    [
      "Inspection ID",
      "Business",
      "District",
      "Category",
      "Officer",
      "Status",
      "Scheduled at",
      "Completed at",
      "Turnaround days",
      "Violations",
      "Critical violations",
      "Violation types",
    ],
    ...rows,
  ];
}

