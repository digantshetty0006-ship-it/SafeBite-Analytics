export type CsvRow = (string | number | null)[];

export interface ReportSummaryDTO {
  filename: string;
  generatedAt: string;
  generatedBy: string;
  periodLabel: string;
  previousLabel: string;
  filters: { label: string; value: string }[];
  scope: { businesses: number; complaints: number; inspections: number };
  kpis: {
    name: string;
    current: string;
    previous: string;
    change: string;
    favourable: string;
    measurement: string;
    formula: string;
  }[];
  districts: {
    district: string;
    businesses: number;
    highRisk: number;
    averageRisk: string;
    inspections: number;
    complaints: number;
    resolved: number;
    overdue: number;
  }[];
  riskTop: {
    name: string;
    district: string;
    category: string;
    score: number;
    tier: string;
    delta: string;
    topFactor: string;
  }[];
  notes: string[];
}

function dateKey(): string {
  return new Date().toISOString().slice(0, 10);
}

function slug(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 40);
}

export function reportFilename(report: string, dataset: AnalyticsDataset): string {
  const scope = dataset.filters.district ? `_${slug(dataset.filters.district)}` : "";
  return `safebite_${report}${scope}_${dateKey()}.csv`;
}

function changeText(comparison: {
  previous: number | null;
  absolute: number | null;
  percent: number | null;
  direction: string;
}): string {
  if (comparison.previous === null) return "no baseline";
  if (comparison.direction === "flat") return "0";
  if (comparison.percent !== null) {
    return `${comparison.percent > 0 ? "+" : ""}${comparison.percent.toFixed(1)}%`;
  }
  if (comparison.absolute !== null) {
    return `${comparison.absolute > 0 ? "+" : ""}${comparison.absolute.toFixed(1)}`;
  }
  return "—";
}

export function buildReportSummary(
  dataset: AnalyticsDataset,
  view: AnalyticsView,
  generatedBy: string
): ReportSummaryDTO {
  const f = dataset.filters;
  return {
    filename: `safebite_management_report_${dateKey()}.pdf`,
    generatedAt: dataset.generatedAt.toLocaleString("en-IN", {
      timeZone: "Asia/Kolkata",
      dateStyle: "medium",
      timeStyle: "short",
    }),
    generatedBy,
    periodLabel: dataset.period.label,
    previousLabel: dataset.period.previousLabel,
    filters: [
      { label: "District", value: f.district || "All districts" },
      { label: "Category", value: f.category ? categoryLabel("en", f.category) : "All categories" },
      { label: "Risk tier", value: f.riskTier || "All tiers" },
      { label: "Complaint status", value: f.complaintStatus || "All statuses" },
      { label: "Inspection status", value: f.inspectionStatus || "All statuses" },
      { label: "Grouping", value: dataset.period.grouping },
    ],
    scope: view.scope,
    kpis: view.kpis.map((kpi) => ({
      name: kpi.definition.name,
      current: formatKpiValue(kpi.value, kpi.definition.unit),
      previous: formatKpiValue(kpi.previous, kpi.definition.unit),
      change: changeText(kpi.comparison),
      favourable:
        kpi.comparison.favourable === "up"
          ? "Favourable"
          : kpi.comparison.favourable === "down"
            ? "Adverse"
            : kpi.comparison.favourable === "flat"
              ? "Flat"
              : "No baseline",
      measurement: kpi.definition.measurement,
      formula: kpi.definition.formula,
    })),
    districts: view.districts.map((d) => ({
      district: d.district,
      businesses: d.businesses,
      highRisk: d.highRisk,
      averageRisk:
        d.averageRiskScore === null ? "—" : d.averageRiskScore.toFixed(1),
      inspections: d.inspectionsCompleted,
      complaints: d.complaintsReceived,
      resolved: d.complaintsResolved,
      overdue: d.overdueOpen,
    })),
    riskTop: view.riskRanking.slice(0, 10).map((r) => ({
      name: r.name,
      district: r.district,
      category: categoryLabel("en", r.category),
      score: r.score,
      tier: r.tier,
      delta:
        r.scoreDelta === null
          ? "—"
          : `${r.scoreDelta > 0 ? "+" : ""}${r.scoreDelta.toFixed(1)}`,
      topFactor: r.topFactor ?? "—",
    })),
    notes: [...view.notes],
  };
}

